// Generates src/face/canonicalFace.ts from MediaPipe's canonical face model.
//
// Usage: node scripts/build-canonical-face.mjs path/to/canonical_face_model.obj
// The .obj comes from
// https://github.com/google-ai-edge/mediapipe/blob/master/mediapipe/modules/face_geometry/data/canonical_face_model.obj
// (Apache License 2.0). Contour loops come from the @mediapipe/tasks-vision package.

import { readFileSync, writeFileSync } from 'node:fs';

const objPath = process.argv[2];
if (!objPath) throw new Error('Pass the path to canonical_face_model.obj');

// The tasks-vision bundle expects a browser-ish global; it only needs `self` to load its constants.
globalThis.self ??= globalThis;
const { FaceLandmarker: FL } = await import('@mediapipe/tasks-vision');

const positions = [];
const uvs = [];
const faces = [];
for (const line of readFileSync(objPath, 'utf8').split('\n')) {
  const p = line.trim().split(/\s+/);
  if (p[0] === 'v') positions.push(p.slice(1, 4).map(Number));
  else if (p[0] === 'vt') uvs.push(p.slice(1, 3).map(Number));
  else if (p[0] === 'f') faces.push(p.slice(1).map((t) => t.split('/').map((n) => Number(n) - 1)));
}

// Faces reference separate vertex / uv indices; each vertex has exactly one uv, so flatten to per-vertex uvs.
const vertexUv = new Array(positions.length);
for (const face of faces) {
  for (const [vi, ti] of face) {
    if (vertexUv[vi] !== undefined && vertexUv[vi] !== ti) throw new Error(`vertex ${vi} has two uvs`);
    vertexUv[vi] = ti;
  }
}
const triangles = faces.flatMap((face) => face.map(([vi]) => vi));

/** Walk an edge list ({start,end} or [a,b]) into one ordered loop. */
function loopFromEdges(edges) {
  const adj = new Map();
  for (const e of edges) {
    const [a, b] = Array.isArray(e) ? e : [e.start, e.end];
    adj.set(a, [...(adj.get(a) ?? []), b]);
    adj.set(b, [...(adj.get(b) ?? []), a]);
  }
  const start = adj.keys().next().value;
  const loop = [start];
  let prev = -1;
  let cur = start;
  for (;;) {
    const next = adj.get(cur).find((n) => n !== prev);
    if (next === start || next === undefined) break;
    loop.push(next);
    prev = cur;
    cur = next;
  }
  if (loop.length !== adj.size) throw new Error(`edges do not form a single loop (${loop.length}/${adj.size})`);
  return loop;
}

/** Orient a loop counter-clockwise as seen from the front (x right, y up). */
function ccw(loop) {
  let area = 0;
  for (let i = 0; i < loop.length; i++) {
    const [x1, y1] = positions[loop[i]];
    const [x2, y2] = positions[loop[(i + 1) % loop.length]];
    area += x1 * y2 - x2 * y1;
  }
  return area >= 0 ? loop : [...loop].reverse();
}

// Mesh boundary = the face oval (the canonical mesh has exactly one open edge loop).
const edgeCount = new Map();
for (let i = 0; i < triangles.length; i += 3) {
  for (const [a, b] of [[0, 1], [1, 2], [2, 0]].map(([p, q]) => [triangles[i + p], triangles[i + q]])) {
    const key = a < b ? `${a},${b}` : `${b},${a}`;
    edgeCount.set(key, (edgeCount.get(key) ?? 0) + 1);
  }
}
const boundary = [...edgeCount].filter(([, n]) => n === 1).map(([k]) => k.split(',').map(Number));
const faceOval = ccw(loopFromEdges(boundary));

// Lips: the connection set holds an outer and an inner loop; the inner one has the smaller area.
const lipEdges = FL.FACE_LANDMARKS_LIPS;
const lipLoops = [];
{
  const remaining = new Set(lipEdges.map((_, i) => i));
  while (remaining.size) {
    const seed = lipEdges[remaining.values().next().value];
    const members = new Set([seed.start, seed.end]);
    let grew = true;
    while (grew) {
      grew = false;
      for (const i of remaining) {
        const e = lipEdges[i];
        if (members.has(e.start) || members.has(e.end)) {
          members.add(e.start);
          members.add(e.end);
          remaining.delete(i);
          grew = true;
        }
      }
    }
    lipLoops.push(ccw(loopFromEdges(lipEdges.filter((e) => members.has(e.start)))));
  }
}
const loopArea = (loop) =>
  Math.abs(loop.reduce((s, v, i) => {
    const [x1, y1] = positions[v];
    const [x2, y2] = positions[loop[(i + 1) % loop.length]];
    return s + x1 * y2 - x2 * y1;
  }, 0));
lipLoops.sort((a, b) => loopArea(a) - loopArea(b));
const innerLips = lipLoops[0];

const rightEye = ccw(loopFromEdges(FL.FACE_LANDMARKS_RIGHT_EYE));
const leftEye = ccw(loopFromEdges(FL.FACE_LANDMARKS_LEFT_EYE));

const fmt = (arr, digits) => arr.map((n) => Number(n.toFixed(digits))).join(',');
const out = `// Generated by scripts/build-canonical-face.mjs — do not edit by hand.
//
// MediaPipe canonical face model (468 vertices), Copyright Google LLC,
// Apache License 2.0: https://github.com/google-ai-edge/mediapipe
//
// Coordinates are centimetres: x to the right as seen in the camera image,
// y up, z towards the camera. Triangles wind counter-clockwise seen from the front.

export const VERTEX_COUNT = ${positions.length};

export const POSITIONS = new Float32Array([${fmt(positions.flat(), 4)}]);

/** Per-vertex texture coordinates (v = 1 at the forehead). */
export const UVS = new Float32Array([${fmt(vertexUv.map((t) => uvs[t]).flat(), 5)}]);

export const TRIANGLES = new Uint16Array([${triangles.join(',')}]);

/** The mesh's open edge, counter-clockwise seen from the front. */
export const FACE_OVAL = [${faceOval.join(',')}];

/** Inner edge of the lips (the mouth opening), counter-clockwise. */
export const INNER_LIPS = [${innerLips.join(',')}];

/** Eyelid contours, counter-clockwise. "Right" is the person's right eye (image left). */
export const RIGHT_EYE = [${rightEye.join(',')}];
export const LEFT_EYE = [${leftEye.join(',')}];
`;
writeFileSync(new URL('../src/face/canonicalFace.ts', import.meta.url), out);
console.log(`wrote src/face/canonicalFace.ts: ${positions.length} vertices, ${triangles.length / 3} triangles,`,
  `oval ${faceOval.length}, inner lips ${innerLips.length}, eyes ${rightEye.length}/${leftEye.length}`);
